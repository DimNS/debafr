#!/bin/sh
# Обёртка вместо системного nginx для dev-стенда: те же самые ключи, что и у
# боевого nginx, но выполняются в контейнере. Приложение вызывает этот скрипт
# через binpaths.nginx и ничего не знает про docker.
#
# Контейнер поднимается здесь же, лениво: шаг Requirements дёргает "nginx -v"
# раньше, чем поднимется compose, так что к моменту первого вызова контейнера
# ещё может не существовать.
#
# Монтируется каталог .dev, а не сам nginx.conf: bind-mount файла отваливается
# при любой записи через temp+rename (sed -i, vim, атомарное сохранение
# редактора) — контейнер продолжает видеть старый inode. У каталога inode
# стабилен, поэтому правки видны сразу. nginx.conf попадает в conf.d и
# подхватывается include-директивой штатного конфига.
#
# Сеть host, потому что proxy_pass ходит на 127.0.0.1:<порт> — внутри
# контейнера это был бы сам контейнер, а не порты, опубликованные compose.

set -e

name=debafr_test_nginx
# Абсолютный путь к каталогу со скриптом: монтировать относительный путь
# нельзя, docker разрешает его от своего CWD, а не от нашего.
dev_dir=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)

docker start "$name" >/dev/null 2>&1 ||
	docker run -d --name "$name" --network host \
		-v "$dev_dir:/etc/nginx/conf.d:ro" nginx:alpine >/dev/null

exec docker exec "$name" nginx "$@"
